// Start server.ts first. All balances, addresses and native RPCs are synthetic.
import assert from 'node:assert/strict';
import fs from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const {expect}=await import(process.env.PLAYWRIGHT_TEST_MODULE || '@playwright/test');
const browser=await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE,headless:true});
const page=await browser.newPage({viewport:{width:1280,height:1000}});
const errors=[], checks={};
page.on('pageerror',e=>errors.push(e.message));
const base=`http://127.0.0.1:${process.env.ZCASH_UI_PORT || 5199}`;
await page.route('**/*',route=>route.request().url().startsWith(base)?route.continue():route.request().resourceType()==='image'?route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><circle cx="32" cy="32" r="30" fill="#ecb244"/><text x="32" y="44" fill="#111" text-anchor="middle" font-size="38">Z</text></svg>'}):route.abort());
const rpc=async(method,params)=> (await (await page.request.post(base+'/__test_rpc',{data:{method,params}})).json()).payload;
const transparent=page.getByRole('button',{name:'Transparent · public',exact:true});
const shielded=page.getByRole('button',{name:'Shielded · private',exact:true});
const tools=page.getByRole('button',{name:/Zcash tools and details/});
try {
 await rpc('testReset');await page.goto(base);
 await expect(transparent).toHaveAttribute('aria-pressed','true');
 await expect(shielded).toBeEnabled();
 await expect(page.getByRole('button',{name:'Privacy',exact:true})).toHaveCount(0);
 await expect(page.getByText('t1'+'A'.repeat(33),{exact:true})).toBeVisible();
 assert(!(await rpc('testCalls')).includes('zcashShieldedInit'));
 checks.standardTransparentDefaultWithoutPrivateInitialization=true;
 await page.screenshot({path:'zcash-transparent.png',fullPage:true});
 await shielded.click();
 await expect(page.getByLabel('Shielded receive',{exact:true})).toBeVisible();
 await expect(page.getByText('t1'+'A'.repeat(33),{exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Show address on KeepKey'})).toBeVisible();
 await expect(tools).toHaveAttribute('aria-expanded','false');
 await expect(page.getByRole('navigation',{name:'Zcash tools',exact:true})).toBeHidden();
 checks.shieldedUsesSharedReceiveAndHidesAdvancedByDefault=true;
 await page.screenshot({path:'zcash-shielded.png',fullPage:true});
 await page.getByRole('button',{name:'Send',exact:true}).first().click();
 await expect(page.getByText('Send from shielded balance',{exact:true})).toBeVisible();
 await expect(page.locator('details.form-aside')).not.toHaveAttribute('open');
 await page.getByPlaceholder('Paste a Zcash address (u1… or t1…)').fill('t1'+'A'.repeat(33));
 await expect(page.getByText('Unshield to a transparent recipient',{exact:true})).toBeVisible();
 await expect(page.getByText('The recipient address and amount will be public. You can pay this address directly from your shielded balance.',{exact:true})).toBeVisible();
 checks.publicRecipientWarningStaysVisibleWithDetailsCollapsed=true;
 await tools.click();
 await page.getByRole('button',{name:'Shield / Unshield',exact:true}).click();
 await expect(page.getByRole('button',{name:'Sync',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'History',exact:true}).click();
 await tools.click();
 await expect(page.getByLabel('Shielded receive',{exact:true})).toBeVisible();
 checks.advancedToolsRemainReachableAndCollapseBackToShieldedReceive=true;
 await page.getByTestId('toggle-privacy').click();
 await expect(shielded).toBeDisabled();
 await expect(page.getByText('Enable Zcash privacy in Settings to check shielded ZEC.',{exact:true}).last()).toBeVisible();
 await expect(page.getByText('t1'+'A'.repeat(33),{exact:true})).toHaveCount(0);
 checks.liveDisableNeverFallsBackToTransparentReceive=true;
 await page.getByTestId('toggle-privacy').click();
 await expect(page.getByLabel('Shielded receive',{exact:true})).toBeVisible();
 await transparent.click();await expect(page.getByText('t1'+'A'.repeat(33),{exact:true})).toBeVisible();
 checks.explicitPoolChangeRestoresTransparentReceive=true;
 await rpc('testReset');await page.goto(base+'?shielded&watchOnly');
 await expect(shielded).toBeDisabled();
 await expect(page.getByText('t1'+'A'.repeat(33),{exact:true})).toHaveCount(0);
 assert(!(await rpc('testCalls')).some(m=>/^zcashShielded(?:Init|Scan)$/.test(m)));
 checks.watchOnlyShieldedDeepLinkHasNoPrivateInitializationOrTransparentFallback=true;
 await expect(page.getByRole('button',{name:'Send',exact:true})).toHaveCount(0);
 await rpc('testReset');await page.goto(base+'?shielded&oldFirmware');
 await expect(shielded).toBeDisabled();
 await expect(page.getByText('t1'+'A'.repeat(33),{exact:true})).toHaveCount(0);
 checks.unsupportedFirmwareNeverFallsBackToTransparentReceive=true;
 await rpc('testReset');await page.goto(base+'?shielded&send');
 await expect(page.getByText('Send from shielded balance',{exact:true})).toBeVisible();
 await expect(tools).toHaveAttribute('aria-expanded','false');
 checks.shieldedSendDeepLinkUsesStandardSendAction=true;
 await page.getByTestId('toggle-privacy').click();
 await expect(page.getByText('Send from shielded balance',{exact:true})).toHaveCount(0);
 await expect(page.getByText('t1'+'A'.repeat(33),{exact:true})).toHaveCount(0);
 await page.getByTestId('toggle-privacy').click();
 await expect(page.getByText('Send from shielded balance',{exact:true})).toBeVisible();
 checks.liveDisableNeverFallsBackToTransparentSend=true;
 await rpc('testReset');await page.goto(base+'?legacyPrivacy');
 await expect(tools).toHaveAttribute('aria-expanded','true');
 await expect(page.getByRole('navigation',{name:'Zcash tools',exact:true})).toBeVisible();
 await tools.click();
 checks.legacyPrivacyDeepLinkOpensToolsInUnifiedPage=true;
 await page.getByRole('button',{name:'Receive',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await expect(page.getByLabel('Shielded receive',{exact:true})).toBeVisible();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'zcash-mobile.png',fullPage:true});
 checks.mobileReceiveFitsViewport=true;
 assert.deepEqual(errors,[]); checks.noPageErrors=true;
 fs.writeFileSync('zcash-ui-results.json',JSON.stringify(checks,null,2)+'\n');
 console.log(JSON.stringify(checks,null,2));
} catch(error) {console.error((await page.locator('body').innerText()).slice(0,7000));throw error;}
finally {await browser.close();}
